export function hydrateCustomInstructions(
  partial?: Partial<CustomInstructionsConfig> | null
): CustomInstructionsConfig {
  const src = partial || {};
  return {
    enabled: typeof src.enabled === 'boolean' ? src.enabled : DEFAULT_CUSTOM_INSTRUCTIONS.enabled,
    style: {
      ...DEFAULT_CUSTOM_INSTRUCTIONS.style,
      ...(src.style || {}),
    },
    models: {
      ...DEFAULT_CUSTOM_INSTRUCTIONS.models,
      ...(src.models || {}),
      workflowOverrides: {
        assistant: {
          ...DEFAULT_CUSTOM_INSTRUCTIONS.models.workflowOverrides.assistant,
          ...(src.models?.workflowOverrides?.assistant || {}),
        },
        voucherDrafting: {
          ...DEFAULT_CUSTOM_INSTRUCTIONS.models.workflowOverrides.voucherDrafting,
          ...(src.models?.workflowOverrides?.voucherDrafting || {}),
        },
        reportInsights: {
          ...DEFAULT_CUSTOM_INSTRUCTIONS.models.workflowOverrides.reportInsights,
          ...(src.models?.workflowOverrides?.reportInsights || {}),
        },
        templateStudio: {
          ...DEFAULT_CUSTOM_INSTRUCTIONS.models.workflowOverrides.templateStudio,
          ...(src.models?.workflowOverrides?.templateStudio || {}),
        },
      },
    },
    knowledge: {
      rules: Array.isArray(src.knowledge?.rules)
        ? src.knowledge.rules.map((r) => ({ ...r }))
        : DEFAULT_CUSTOM_INSTRUCTIONS.knowledge.rules.map((r) => ({ ...r })),
      glossary: Array.isArray(src.knowledge?.glossary)
        ? src.knowledge.glossary.map((g) => ({ ...g }))
        : DEFAULT_CUSTOM_INSTRUCTIONS.knowledge.glossary.map((g) => ({ ...g })),
      documents: Array.isArray(src.knowledge?.documents)
        ? src.knowledge.documents.map((d): KnowledgeDocumentItem => {
            const lowerName = String(d.filename || '').toLowerCase();
            const inferredType: DocumentFileType = d.fileType
              ? d.fileType
              : lowerName.endsWith('.pdf')
                ? 'PDF'
                : lowerName.endsWith('.csv') || lowerName.endsWith('.tsv')
                  ? 'CSV'
                  : lowerName.endsWith('.md')
                    ? 'MD'
                    : lowerName.endsWith('.json')
                      ? 'JSON'
                      : 'TXT';
            return {
              ...d,
              fileType: inferredType,
              scope: d.scope === 'assistant' || d.scope === 'reporting' ? d.scope : 'global',
              vectorStatus:
                d.vectorStatus === 'vectorized' || d.vectorStatus === 'error'
                  ? d.vectorStatus
                  : 'pending',
              embeddingModel: d.embeddingModel || 'gemini-embedding-2',
              embeddingDimensions: typeof d.embeddingDimensions === 'number' ? d.embeddingDimensions : 0,
              chunkCount: typeof d.chunkCount === 'number' ? d.chunkCount : 0,
              chunkSizeTarget: typeof d.chunkSizeTarget === 'number' ? d.chunkSizeTarget : 900,
              vectorizedAt: d.vectorizedAt ?? null,
              summaryPreview:
                d.summaryPreview ||
                String(d.extractedText || '')
                  .replace(/\s+/g, ' ')
                  .trim()
                  .slice(0, 180),
            };
          })
        : [],
    },
    prompts: {
      ...DEFAULT_CUSTOM_INSTRUCTIONS.prompts,
      ...(src.prompts || {}),
      workflowPrompts: {
        ...DEFAULT_CUSTOM_INSTRUCTIONS.prompts.workflowPrompts,
        ...(src.prompts?.workflowPrompts || {}),
      },
    },
  };
}

