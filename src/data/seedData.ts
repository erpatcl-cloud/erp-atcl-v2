function buildPopulatedState(): LedgerState {
  const accounts = buildInitialAccounts();
  const accountMap = new Map(accounts.map((a) => [a.code, a]));
  const journalLines: JournalLine[] = [];
  const postedTransactions: PostedTransaction[] = [];

  FY2024_25_STATUTORY_VOUCHERS.forEach((v, vIdx) => {
    const postTs = `${v.date}T17:00:00.000Z`;
    const debitLines = v.lines.filter((l) => l.debit > 0);
    const creditLines = v.lines.filter((l) => l.credit > 0);
    const mainCredit = creditLines[0];
    const mainDebit = debitLines[0];

    v.lines.forEach((line, lIdx) => {
      const acc = accountMap.get(line.glCode);
      const glName = acc?.name || line.glCode;
      const journalId = `JRN-${String(vIdx + 1).padStart(3, '0')}-${lIdx + 1}`;
      const transactionId = `TX-${String(vIdx + 1).padStart(3, '0')}-${lIdx + 1}`;

      journalLines.push({
        journalId,
        date: v.date,
        voucherNo: v.voucherNo,
        description: v.description,
        glCode: line.glCode,
        glName,
        debit: line.debit,
        credit: line.credit,
        reference: v.reference,
        counterparty: v.counterparty,
        enteredBy: v.enteredBy,
        approvalStatus: 'APPROVED',
        postingStatus: 'POSTED',
        validationRemarks: 'Statutory FY 2024-25 Opening/Seeded Voucher',
      });

      const contra = line.debit > 0 ? mainCredit : mainDebit;
      const contraAcc = contra ? accountMap.get(contra.glCode) : undefined;

      postedTransactions.push({
        postTimestamp: postTs,
        journalId,
        voucherNo: v.voucherNo,
        date: v.date,
        type: line.debit > 0 ? 'Debit Post' : 'Credit Post',
        description: v.description,
        reference: v.reference,
        counterparty: v.counterparty,
        glCode: line.glCode,
        glName,
        contraCode: contra?.glCode || '',
        contraName: contraAcc?.name || contra?.glCode || '',
        debit: line.debit,
        credit: line.credit,
        enteredBy: v.enteredBy,
        registerSynced: 'SYNCED',
        transactionId,
      });
    });
  });

  const registers: Record<string, AccountRegisterBook> = {};
  for (const acc of accounts) {
    registers[acc.code] = {
      glCode: acc.code,
      fileId: acc.registerFileId || `REG-${acc.code}`,
      fileName: acc.registerFileName || `${acc.code} - ${acc.name}`,
      createdAt: '2024-07-01T09:00:00.000Z',
      lastSyncedAt: '2025-06-30T18:00:00.000Z',
      entries: [],
    };
  }

  for (const acc of accounts) {
    const accTx = postedTransactions.filter((t) => t.glCode === acc.code);
    let runningBal = acc.openingBalance;
    const entries: RegisterEntry[] = accTx.map((t) => {
      runningBal =
        acc.normalBalance === 'Credit'
          ? runningBal + t.credit - t.debit
          : runningBal + t.debit - t.credit;
      const balanceType: 'Dr' | 'Cr' =
        runningBal >= 0
          ? acc.normalBalance === 'Debit'
            ? 'Dr'
            : 'Cr'
          : acc.normalBalance === 'Debit'
            ? 'Cr'
            : 'Dr';
      return {
        date: t.date,
        voucherNo: t.voucherNo,
        type: t.type,
        description: t.description,
        reference: t.reference,
        counterparty: t.counterparty,
        contraCode: t.contraCode,
        contraName: t.contraName,
        debit: t.debit,
        credit: t.credit,
        runningBalance: runningBal,
        balanceType,
        enteredBy: t.enteredBy,
        entryTimestamp: t.postTimestamp,
        transactionId: t.transactionId,
      };
    });
    registers[acc.code].entries = entries;
  }

  return {
    datasetVersion: CURRENT_DATASET_VERSION,
    config: { ...DEFAULT_CONFIG },
    accounts,
    journalLines,
    postedTransactions,
    registers,
    auditLogs: [
      {
        timestamp: '2025-06-30T18:00:00.000Z',
        logId: 'AUD-0003',
        userEmail: DEFAULT_CONFIG.operatorEmail,
        module: 'AUDIT_ENGINE',
        action: 'RECONCILIATION',
        details:
          'Verified FY 2024-25 Closing Trial Balance and synchronized across 54 linked Register Books.',
        status: 'SUCCESS',
      },
    ],
    products: buildInitialProducts(),
    customers: buildInitialCustomers(),
    suppliers: buildInitialSuppliers(),
    localPurchaseOrders: buildInitialLocalPOs(),
    importLCs: buildInitialImportLCs(),
    inventorySerials: buildInitialSerialRegister(),
    salesOrders: buildInitialSalesOrders(),
    posTransactions: buildInitialPosTransactions(),
    warrantyClaims: buildInitialWarrantyClaims(),
    serviceJobs: buildInitialServiceJobs(),
    spareParts: buildInitialSpareParts(),
    vouchers: buildInitialVouchers(),
    templates: buildInitialTemplates(),
    goodsReceipts: [],
    purchaseInvoices: [],
  };
}

